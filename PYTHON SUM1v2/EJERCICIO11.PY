#11 Realiza un programa que introduciendo el valor del lado de un cuadrado nos devuelva por pantalla en el area y el perimetro. 
lado = int(input("INTRODUCE EL VALOR DEL LADO DEL CUADRADO: "))
area = lado ** 2
perimetro = lado * 4
print("EL AREA DEL CUADRADO ES:", area)
print("EL PERIMETRO DEL CUADRADO ES:", perimetro)